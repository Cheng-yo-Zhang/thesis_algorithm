def count(text: str):
    chinese = re.findall(r'[一-鿿]', text)
    english_words = re.findall(r'[A-Za-z]+', text)
    digits = re.findall(r'[0-9]+', text)
    no_space = re.sub(r'\s+', '', text)
    return {
        '中文字': len(chinese),
        '英文詞': len(english_words),
        '數字串': len(digits),
        '總字元(去空白)': len(no_space),
        '中文字+英文詞': len(chinese) + len(english_words) + len(digits),
    }


